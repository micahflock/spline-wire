"""The DXF that output.dxf_text writes, as a template for the TypeScript
writer (web/src/pipeline/dxf-template.ts) and golden files to check it
(web/src/pipeline/golden/dxf.json.gz).

ezdxf writes the same file for any curve but for: the drawing's dates
($TDCREATE, $TDUPDATE), two GUIDs, two "written by ezdxf" time stamps, the
handles of the entities and of the four objects made after them, and the
ENTITIES section itself (one SPLINE through the points, one POINT per
point). The template is ezdxf's own output with those replaced by
placeholders; this script checks that the templates made from curves of
different lengths are identical, so nothing else varies. The TypeScript
writer must give the golden files byte for byte, but for the dates, GUIDs
and time stamps (masked) and the last digits of the spline's numbers.

    uv run python web/scripts/golden_dxf.py

ezdxf lists its CLASS records in an order that follows Python's string hash
seed (two of the fifteen swap places from one run to the next), so the .exe
and the browser have always written both orders. The script runs itself with
PYTHONHASHSEED=0 so the template it writes does not change from run to run;
the tests compare the CLASS records as a set.
"""
from __future__ import annotations

import gzip
import json
import os
import re
import sys
from pathlib import Path

import ezdxf
import numpy as np

from splinewire.output import dxf_text

REPO = Path(__file__).resolve().parents[2]
TEMPLATE = REPO / "web" / "src" / "pipeline" / "dxf-template.ts"
GOLDEN = REPO / "web" / "src" / "pipeline" / "golden" / "dxf.json.gz"


def template(points: np.ndarray) -> str:
    lines = dxf_text(points).split("\n")
    n = len(points)
    first = 0x31                      # the SPLINE's handle; the points follow
    after = [f"{first + n + k:X}" for k in range(1, 5)]     # two APPIDs, the DICTIONARYVAR, $HANDSEED
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        prev = lines[i - 1] if i else ""
        if line == "ENTITIES" and prev.strip() == "2":
            out.append(line)
            out.append("{{ENTITIES}}")
            i += 1
            while lines[i] != "ENDSEC":
                i += 1
            out.append(lines[i - 1])      # the "  0" before ENDSEC
            out.append("ENDSEC")
            i += 1
            continue
        var = lines[i - 2] if i >= 2 else ""
        if var in ("$TDCREATE", "$TDUPDATE", "$FINGERPRINTGUID", "$VERSIONGUID", "$HANDSEED"):
            out.append("{{" + var[1:] + "}}")
        elif re.fullmatch(r"\d+(\.\d+)+ @ .*", line):
            out.append("{{MARKER}}")
        elif prev.strip() in ("5", "350", "330") and line in after[:3]:
            out.append("{{H%d}}" % after.index(line))
        else:
            out.append(line)
        i += 1
    return "\n".join(out)


def entities(points: np.ndarray) -> str:
    lines = dxf_text(points).split("\n")
    i = lines.index("ENTITIES")
    j = lines.index("ENDSEC", i)
    return "\n".join(lines[i + 1:j - 1])


def main() -> None:
    if os.environ.get("PYTHONHASHSEED") != "0":
        os.execve(sys.executable, [sys.executable, *sys.argv], {**os.environ, "PYTHONHASHSEED": "0"})
    rng = np.random.default_rng(11)
    curves = [
        np.array([[0.0, 0.0], [10.0, 2.0], [20.0, 0.0]]),
        np.array([[i * 10.0, (i % 3) * 2.0] for i in range(6)]),
        np.cumsum(rng.normal(0, 5, (13, 2)), axis=0),
        np.cumsum(rng.normal(0, 5, (30, 2)), axis=0),
        np.array([[0.0, 0.0], [10.0, 0.0]]),
    ]
    templates = {template(c) for c in curves[:4] + curves[:1]}
    if len(templates) != 1:
        raise SystemExit("the DXF varies in more than the template's placeholders")
    text = templates.pop()
    TEMPLATE.write_text(
        "// Generated by web/scripts/golden_dxf.py from ezdxf's own output (output.dxf_text): the\n"
        "// DXF with its variable parts as placeholders in double braces. Do not edit; run the script.\n"
        f"export const EZDXF_VERSION = {json.dumps(ezdxf.__version__)};\n"
        f"export const DXF_TEMPLATE = {json.dumps(text)};\n", encoding="utf-8")
    golden = [{"points": c.tolist(), "dxf": dxf_text(c)} for c in curves]
    with gzip.GzipFile(GOLDEN, "wb", mtime=0) as f:
        f.write(json.dumps({"ezdxf": ezdxf.__version__, "curves": golden}).encode("utf-8"))
    print(f"template {len(text)} chars -> {TEMPLATE}; {len(golden)} golden files -> {GOLDEN}")


if __name__ == "__main__":
    main()
